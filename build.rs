//! Embeds the web kit's style and behavior files (`src/web/kit.css`, `kit.js`, `motion.css`,
//! `motion.js`) into the compiler when they exist: `nyra build` of a `use web` program picks the
//! parts of them a site uses (see `src/web/assets.rs`). A file that is not there yet is embedded
//! as an empty text, so the compiler builds at every stage of the web work. No crates.

use std::fmt::Write;
use std::path::Path;

fn main() {
    let out = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
    let mut code = String::from("// generated by build.rs: the web kit's files (empty when a file is missing)\n");
    for (name, file) in [("KIT_CSS", "kit.css"), ("KIT_JS", "kit.js"), ("MOTION_CSS", "motion.css"), ("MOTION_JS", "motion.js")] {
        let path = Path::new("src").join("web").join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        let full = std::fs::canonicalize(&path).ok();
        match full {
            Some(p) if p.is_file() => {
                let _ = writeln!(code, "pub const {name}: &str = include_str!({:?});", p.display().to_string());
            }
            _ => {
                let _ = writeln!(code, "pub const {name}: &str = \"\";");
            }
        }
    }
    // a file that appears later must be picked up: watch the folder too
    println!("cargo:rerun-if-changed=src/web");
    println!("cargo:rerun-if-changed=build.rs");
    std::fs::write(Path::new(&out).join("web_assets.rs"), code).expect("cannot write web_assets.rs");
}
